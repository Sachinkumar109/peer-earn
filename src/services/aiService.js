import { getAI, getGenerativeModel, GoogleAIBackend } from "firebase/ai";
import { app } from "../firebase/config";

/*
  Peer-Earn AI Answer Analyzer

  IMPORTANT:
  This is NOT a guaranteed AI detector.

  It evaluates:
  - relevance
  - correctness
  - completeness
  - clarity
  - possible AI-assisted writing signals

  The AI-assistance signal is only an indication,
  not proof that the answer was generated by AI.
*/

let model = null;

const getAIModel = () => {
  if (!app) {
    throw new Error(
      "Firebase is not configured. AI Answer Analyzer requires Firebase."
    );
  }

  if (!model) {
    const ai = getAI(app, {
      backend: new GoogleAIBackend(),
    });

    model = getGenerativeModel(ai, {
      model: "gemini-3.8-flash",
      generationConfig: {
        temperature: 0.1,
        responseMimeType: "application/json",
        responseSchema: {
          type: "object",
          properties: {
            relevanceScore: {
              type: "number",
              description:
                "How directly the submitted answer addresses the question. 0 to 100.",
            },

            correctnessScore: {
              type: "number",
              description:
                "How technically correct the answer appears. 0 to 100.",
            },

            completenessScore: {
              type: "number",
              description:
                "How completely the answer solves the question. 0 to 100.",
            },

            clarityScore: {
              type: "number",
              description:
                "How clear and understandable the explanation is. 0 to 100.",
            },

            aiAssistanceSignal: {
              type: "string",
              enum: [
                "unlikely",
                "possible",
                "likely",
                "insufficient_evidence",
              ],
            },

            aiSignalConfidence: {
              type: "string",
              enum: ["low", "medium", "high"],
            },

            summary: {
              type: "string",
            },

            strengths: {
              type: "array",
              items: {
                type: "string",
              },
            },

            missingPoints: {
              type: "array",
              items: {
                type: "string",
              },
            },

            errors: {
              type: "array",
              items: {
                type: "string",
              },
            },

            suggestions: {
              type: "array",
              items: {
                type: "string",
              },
            },
          },

          required: [
            "relevanceScore",
            "correctnessScore",
            "completenessScore",
            "clarityScore",
            "aiAssistanceSignal",
            "aiSignalConfidence",
            "summary",
            "strengths",
            "missingPoints",
            "errors",
            "suggestions",
          ],
        },
      },
    });
  }

  return model;
};


export const analyzeAnswer = async ({
  question,
  subject = "",
  classLevel = "",
  answer,
}) => {
  if (!question?.trim()) {
    throw new Error("Question is required.");
  }

  if (!answer?.trim()) {
    throw new Error("Answer is required.");
  }

  const aiModel = getAIModel();

  const prompt = `
You are the Answer Quality Analyzer for a student peer-learning platform called Peer-Earn.

Your job is to evaluate a student's submitted answer to another student's doubt.

QUESTION:
${question}

SUBJECT:
${subject || "Not specified"}

CLASS / LEVEL:
${classLevel || "Not specified"}

SUBMITTED ANSWER:
${answer}

Evaluate the answer carefully.

IMPORTANT RULES:

1. Judge whether the answer actually addresses the question.
2. Check technical/factual correctness.
3. Check whether important parts of the question are unanswered.
4. Check clarity and educational usefulness.
5. Identify concrete mistakes if present.
6. Suggest specific improvements.
7. Consider whether the wording contains signals commonly associated with AI-assisted writing.

IMPORTANT ABOUT AI DETECTION:

You MUST NOT claim that text is definitely AI-generated.

Text alone cannot reliably prove authorship.

Use:
- "unlikely" when there are few AI-like signals.
- "possible" when there are some AI-like signals.
- "likely" only when there are strong stylistic signals.
- "insufficient_evidence" when there is not enough evidence.

The AI-assistance field is only a signal and must never be treated as proof.

Return only the requested JSON structure.
`;

  try {
    const result = await aiModel.generateContent(prompt);

    const text = result.response.text();

    const parsed = JSON.parse(text);

    return {
      relevanceScore: clampScore(parsed.relevanceScore),
      correctnessScore: clampScore(parsed.correctnessScore),
      completenessScore: clampScore(parsed.completenessScore),
      clarityScore: clampScore(parsed.clarityScore),

      aiAssistanceSignal:
        parsed.aiAssistanceSignal || "insufficient_evidence",

      aiSignalConfidence:
        parsed.aiSignalConfidence || "low",

      summary:
        parsed.summary || "No summary available.",

      strengths: Array.isArray(parsed.strengths)
        ? parsed.strengths
        : [],

      missingPoints: Array.isArray(parsed.missingPoints)
        ? parsed.missingPoints
        : [],

      errors: Array.isArray(parsed.errors)
        ? parsed.errors
        : [],

      suggestions: Array.isArray(parsed.suggestions)
        ? parsed.suggestions
        : [],
    };
  } catch (error) {
    console.error("AI Answer Analyzer error:", error);

    throw new Error(
      "Unable to analyze the answer right now. Please try again."
    );
  }
};


const clampScore = (value) => {
  const number = Number(value);

  if (!Number.isFinite(number)) {
    return 0;
  }

  return Math.max(0, Math.min(100, Math.round(number)));
};